 * and a mangled string for GPIM. Nothing here comes from the model.
 *
 * Every listed company has a row. That is the point rather than a milestone: the fault was names
 * arriving from whatever a run happened to read, and a table with holes in it leaves that route
 * open for whichever stock falls in one. [EgxCatalog.enrich] refuses a model-written name whatever
 * this table holds, so a listing added to the exchange tomorrow shows a bare ticker until its row
 * is written, and never a name that changes between runs.
 *
 * Compiled in rather than shipped as an asset, for the reason StockLogos is a `when` over literals:
